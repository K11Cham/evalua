// Golden-set evaluation: runs every fake transcript through the full pipeline and reports accuracy.
//   npm run eval                 → all files, writes docs/ACCURACY.md and docs/accuracy.json
//   npm run eval -- mx-sep -v    → matching files only, with per-file misses (does not rewrite the report)
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { evaluate, runExtraction } from '../../src/core/pipeline.ts';
import { seedKb } from '../../src/kb/index.ts';
import type { Truth } from '../fakegen/types.ts';
import { closeOcr, ingestFile } from './node-ingest.ts';
import { scoreFile, type FileScore } from './score.ts';

const args = process.argv.slice(2);
const verbose = args.includes('-v');
const noCache = args.includes('--no-cache');
const filters = args.filter((a) => !a.startsWith('-'));
const manifest = JSON.parse(readFileSync('fixtures/fake/manifest.json', 'utf8')) as Truth[];
const targets = manifest.filter((m) => !filters.length || filters.some((f) => m.file.includes(f)));
const kb = seedKb();
const district = kb.districts.find((d) => d.id === 'generic-22')!;

const scores: FileScore[] = [];
for (const t of targets) {
  const t0 = Date.now();
  const doc = await ingestFile(path.join('fixtures/fake', t.file), !noCache);
  const ex = runExtraction(doc, kb);
  const ev = evaluate(ex, kb, district);
  const s = scoreFile(t, ex, ev, doc.engine, Date.now() - t0);
  scores.push(s);
  const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : '—');
  console.log(
    `${t.file.padEnd(26)} sys ${s.systemOk ? '✓' : '✗'} name ${s.nameOk ? '✓' : '✗'} dob ${s.dobOk ? '✓' : '✗'}  courses ${s.found}/${s.truthCourses} (+${s.spurious})  grade ${pct(s.gradeOk, s.found)}  level ${pct(s.levelOk, s.levelTotal)}  subject ${pct(s.conceptOk, s.found)}  US ${pct(s.letterOk, s.found)}`,
  );
  if (verbose || filters.length) for (const m of s.misses.slice(0, 40)) console.log('     · ' + m);
}
await closeOcr();

const sum = (f: (s: FileScore) => number, set = scores) => set.reduce((a, s) => a + f(s), 0);
const P = (a: number, b: number) => (b ? `${((100 * a) / b).toFixed(1)}%` : '—');
const count = (f: (s: FileScore) => boolean, set = scores) => `${set.filter(f).length}/${set.length}`;

function table(set: FileScore[]): string {
  const rows = [
    ['Education system identified', count((s) => s.systemOk, set)],
    ['Student name', count((s) => s.nameOk, set)],
    ['Date of birth', count((s) => s.dobOk, set)],
    ['Student ID', count((s) => s.idOk, set)],
    ['School name', `${set.filter((s) => s.schoolOk).length}/${set.filter((s) => s.schoolOk !== null).length}`],
    ['Courses found (recall)', `${P(sum((s) => s.found, set), sum((s) => s.truthCourses, set))} (${sum((s) => s.found, set)}/${sum((s) => s.truthCourses, set)})`],
    ['Rows that are not real courses', String(sum((s) => s.spurious, set))],
    ['Course name read exactly', P(sum((s) => s.exactName, set), sum((s) => s.found, set))],
    ['Grade correct (of courses found)', P(sum((s) => s.gradeOk, set), sum((s) => s.found, set))],
    ['Credits correct (where printed)', P(sum((s) => s.creditsOk, set), sum((s) => s.creditsTotal, set))],
    ['Hours correct (where printed)', P(sum((s) => s.hoursOk, set), sum((s) => s.hoursTotal, set))],
    ['US grade level correct', P(sum((s) => s.levelOk, set), sum((s) => s.levelTotal, set))],
    ['Subject matched to the expected concept', P(sum((s) => s.conceptOk, set), sum((s) => s.found, set))],
    ['US letter grade correct', P(sum((s) => s.letterOk, set), sum((s) => s.found, set))],
    ['English name close to the reference translation', P(sum((s) => s.translationOk, set), sum((s) => s.translationTotal, set))],
    ['Language of instruction (English-medium or not) correct', `${set.filter((s) => s.instructionOk).length}/${set.filter((s) => s.instructionOk !== null).length}`],
    ['Redacted files: student details kept out (never read as text)', set.some((s) => s.redactionOk !== null) ? `${set.filter((s) => s.redactionOk).length}/${set.filter((s) => s.redactionOk !== null).length}` : '—'],
  ];
  return '| Measure | Result |\n|---|---|\n' + rows.map((r) => `| ${r[0]} | ${r[1]} |`).join('\n') + '\n';
}

if (!filters.length) {
  const text = scores.filter((s) => s.format === 'pdf' || s.format === 'docx');
  const raster = scores.filter((s) => s.format !== 'pdf' && s.format !== 'docx');
  const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : '—');
  let md = `# Accuracy report\n\n`;
  md += `Generated by \`npm run eval\` on ${new Date().toISOString().slice(0, 10)}. Pipeline: rules only (no language model). District profile used for matching: ${district.name}.\n\n`;
  md += `The golden set is ${scores.length} files rendered from ${new Set(scores.map((s) => s.file.split('.')[0])).size} **fictitious** records in \`fixtures/fake/\` (see \`tools/fakegen\`). Each has a known correct answer.\n\n`;
  md += `## Read this first\n\n`;
  md += `- The fake transcripts and the parser were written by the same author, so layouts the generator does not produce are not measured here. Real documents will do worse than these numbers, especially handwritten, stamped-over, or very low-resolution ones.\n`;
  md += `- “Subject matched” compares against one reasonable expected subject per course. Some are judgement calls (for example, how to classify a combined history-geography course).\n`;
  md += `- “US letter grade” checks that the cited conversion table was applied correctly. It does not show that the table is the right policy for your district.\n`;
  md += `- English names come from dictionaries, not a translator, so wording differs from a human translation even when the subject is right.\n\n`;
  md += `## All files (${scores.length})\n\n${table(scores)}\n`;
  md += `## Text PDFs and Word files (${text.length})\n\n${table(text)}\n`;
  md += `## Scans and phone photos, read by OCR (${raster.length})\n\n${table(raster)}\n`;
  md += `## Per file\n\n| File | Read by | System | Student | Courses found | Extra rows | Grade | Level | Subject | US grade |\n|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const s of scores) {
    md += `| ${s.file} | ${s.engine} | ${s.systemOk ? 'yes' : 'no'} | ${s.nameOk && s.dobOk ? 'yes' : s.nameOk ? 'name only' : s.dobOk ? 'birth date only' : 'no'} | ${s.found}/${s.truthCourses} | ${s.spurious} | ${pct(s.gradeOk, s.found)} | ${pct(s.levelOk, s.levelTotal)} | ${pct(s.conceptOk, s.found)} | ${pct(s.letterOk, s.found)} |\n`;
  }
  md += `\n## What went wrong\n\nEvery miss, so the weak spots are visible:\n\n`;
  for (const s of scores) {
    if (!s.misses.length) continue;
    md += `**${s.file}**\n\n${s.misses.slice(0, 25).map((m) => `- ${m}`).join('\n')}${s.misses.length > 25 ? `\n- …and ${s.misses.length - 25} more` : ''}\n\n`;
  }
  writeFileSync('docs/ACCURACY.md', md);
  writeFileSync('docs/accuracy.json', JSON.stringify({ generated: new Date().toISOString(), district: district.id, scores: scores.map(({ misses, ...r }) => ({ ...r, missCount: misses.length })) }, null, 1) + '\n');
  console.log('\n' + table(scores));
  console.log('wrote docs/ACCURACY.md');
}
