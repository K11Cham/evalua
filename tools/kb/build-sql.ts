// Writes migrations/seed.sql from the knowledge-base source files, for loading into Cloudflare D1:
//   npm run kb:sql && npx wrangler d1 execute evalua-kb --remote --file=migrations/seed.sql
import { writeFileSync } from 'node:fs';
import { seedKb } from '../../src/kb/index.ts';

const kb = seedKb();
const q = (s: string | undefined | null) => (s == null ? 'NULL' : `'${s.replace(/'/g, "''")}'`);
const rows: string[] = [];
const add = (kind: string, id: string, pos: number, data: unknown, title?: string, url?: string, added = '2026-11-15') =>
  rows.push(
    `INSERT OR REPLACE INTO kb_items (kind, id, school_year, position, data, source_title, source_url, added_on) VALUES (${q(kind)}, ${q(id)}, ${q(kb.schoolYear)}, ${pos}, ${q(JSON.stringify(data))}, ${q(title)}, ${q(url)}, ${q(added)});`,
  );

kb.concepts.forEach((c, i) => add('concept', c.id, i, c, 'NCES School Courses for the Exchange of Data (SCED)', 'https://nces.ed.gov/forum/sced.asp'));
kb.systems.forEach((s, i) => add('system', s.id, i, s, s.provenance.source.title, s.provenance.source.url, s.provenance.addedOn));
kb.districts.forEach((d, i) => add('district', d.id, i, d, d.provenance.source.title, d.provenance.source.url, d.provenance.addedOn));

writeFileSync('migrations/seed.sql', `-- Generated by tools/kb/build-sql.ts. Do not edit by hand.\nDELETE FROM kb_items WHERE school_year = ${q(kb.schoolYear)};\n${rows.join('\n')}\n`);
console.log(`migrations/seed.sql: ${rows.length} rows for ${kb.schoolYear}`);
